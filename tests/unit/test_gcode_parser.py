class TestEstimatePrintParameters:
    """Функция estimate_print_parameters — fallback на размер файла."""

    def test_with_parsed_data(self, tmp_path):
        """С данными слайсера — возвращает распарсенные значения."""
        gcode_file = tmp_path / "test_est.gcode"
        gcode_file.write_text(
            "; generated by OrcaSlicer 2.0.0\n"
            "; estimated printing time (normal mode) = 1h 30m\n"
            "; filament used [g] = 25.5\n"
            "G28\n"
        )
        filament, time_min = estimate_print_parameters(str(gcode_file))
        assert filament == 25.5
        assert time_min == 90.0

    def test_fallback_on_unknown_slicer(self, tmp_path):
        """Без данных слайсера — fallback на размер файла."""
        gcode_file = tmp_path / "test_fallback.gcode"
        gcode_file.write_text("G28\nG1 X0 Y0 Z0.3\n")
        filament, time_min = estimate_print_parameters(str(gcode_file))
        # Fallback: filament = 5.0 + size_kb * 0.05, time = 30.0 + size_kb * 0.2
        assert filament > 0
        assert time_min > 0
